#!/usr/bin/env node
/**
 * Regenerates src/lib/data/enkaData.generated.ts from Enka.Network's public
 * data store (https://github.com/EnkaNetwork/API-docs/tree/master/store/gi).
 *
 * Usage: node scripts/generate-enka-data.mjs
 *
 * Run after each patch once Enka's store includes the new characters and
 * weapons, then run the enka and characterData tests.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const STORE = 'https://raw.githubusercontent.com/EnkaNetwork/API-docs/master/store/gi';
const OUTPUT = fileURLToPath(new URL('../src/lib/data/enkaData.generated.ts', import.meta.url));

const ELEMENTS = {
  Fire: 'Pyro',
  Water: 'Hydro',
  Wind: 'Anemo',
  Electric: 'Electro',
  Grass: 'Dendro',
  Ice: 'Cryo',
  Rock: 'Geo',
};

async function fetchJson(file) {
  const response = await fetch(`${STORE}/${file}`);
  if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
  return response.json();
}

const [avatars, weapons, locs] = await Promise.all([
  fetchJson('avatars.json'),
  fetchJson('weapons.json'),
  fetchJson('locs.json'),
]);
const en = locs.en;
const nameOf = (hash) => {
  const name = en[String(hash)];
  if (!name) throw new Error(`No English name for text hash ${hash}`);
  return name;
};

const characters = [];
const skillOrder = [];
const travelerElements = [];

for (const [id, avatar] of Object.entries(avatars).sort(([a], [b]) => a.localeCompare(b))) {
  if (avatar.SkillOrder?.length === 3) skillOrder.push([id, avatar.SkillOrder]);

  const [avatarId, depotId] = id.split('-');
  if (depotId) {
    const element = ELEMENTS[avatar.Element];
    if (element) travelerElements.push([Number(depotId), element]);
    continue;
  }
  characters.push([
    Number(avatarId),
    nameOf(avatar.NameTextMapHash),
    avatar.SideIconName.replace('/ui/UI_AvatarIcon_Side_', '').replace('.png', ''),
  ]);
}

const weaponNames = Object.entries(weapons)
  .map(([id, weapon]) => [Number(id), nameOf(weapon.NameTextMapHash)])
  .sort(([a], [b]) => a - b);

const str = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lines = [
  '// Generated by scripts/generate-enka-data.mjs from Enka.Network\'s data store.',
  '// Do not edit by hand; re-run the script after each patch.',
  '',
  '/** avatarId -> English name and side-icon name */',
  'export const ENKA_CHARACTERS: Record<number, { name: string; icon: string }> = {',
  ...characters.map(([id, name, icon]) => `  ${id}: { name: ${str(name)}, icon: ${str(icon)} },`),
  '};',
  '',
  '/**',
  ' * Normal attack, elemental skill and burst skill IDs, keyed by avatarId (or',
  ' * `avatarId-skillDepotId` for the Traveler). skillLevelMap is keyed by these.',
  ' */',
  'export const ENKA_SKILL_ORDER: Record<string, readonly [number, number, number]> = {',
  ...skillOrder.map(([id, order]) => `  '${id}': [${order.join(', ')}],`),
  '};',
  '',
  '/** Traveler skillDepotId -> element */',
  'export const ENKA_TRAVELER_ELEMENTS: Record<number, string> = {',
  ...travelerElements.map(([depot, element]) => `  ${depot}: '${element}',`),
  '};',
  '',
  '/** Weapon itemId -> English name */',
  'export const ENKA_WEAPON_NAMES: Record<number, string> = {',
  ...weaponNames.map(([id, name]) => `  ${id}: ${str(name)},`),
  '};',
  '',
];

writeFileSync(OUTPUT, lines.join('\n'));
console.log(
  `Wrote ${characters.length} characters, ${skillOrder.length} skill orders, ${weaponNames.length} weapons to ${OUTPUT}`
);
